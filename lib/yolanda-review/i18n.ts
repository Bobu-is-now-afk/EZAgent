export function t(locale: ReviewLocale, text: string): string {
  return locale === 'zh-Hant' ? zhHant[text] ?? text : text
}

export function localizeRuntimeText(locale: ReviewLocale, text?: string): string | undefined {
  if (!text || locale === 'en') return text
  const exact = zhHant[text]
  if (exact) return exact
  return text
    .replace(/(\d+) blockers?/, '$1 個阻塞項')
    .replace('Confirm task assumptions.', '確認任務假設。')
    .replace('Manager role is required.', '需要經理角色。')
    .replace('Wait for current calculation.', '等待目前版本完成計算。')
    .replace('Current calculation is not valid for this version.', '目前計算結果不適用於此版本。')
    .replace('Review numeric results.', '審核數值結果。')
    .replace('Review message drafts.', '審核訊息草稿。')
    .replace('At least one included record is required.', '至少需要一筆納入紀錄。')
    .replace(/Resolve (\d+) hard blockers?\./, '處理 $1 個嚴重阻塞項。')
    .replace(/Acknowledge (\d+) warnings?\./, '確認 $1 個警告並填寫理由。')
    .replace(/Close open editors: (.+)\./, '先關閉未儲存的編輯區：$1。')
    .replace(/Saved as v(\d+); current approval is no longer valid\./, '已儲存為 v$1；目前批准已失效。')
    .replace(/Approved v(\d+) for export and manual follow-up only\./, 'v$1 已批准，只供匯出及人工跟進。')
    .replace(/Save refused: next revision must be v(\d+)\./, '儲存被拒絕：下一版本必須是 v$1。')
    .replace('Approval refused:', '批准被拒絕：')
    .replace('Import failed:', '匯入失敗：')
    .replace(/Generated (JSON|CSV|TXT) download for approved v(\d+)\. Browser save cannot be verified\./, '已為批准版本 v$2 產生 $1 下載；無法驗證瀏覽器是否完成儲存。')
}
